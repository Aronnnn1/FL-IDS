"""Write the full-pool configs: configs/full/c<clients>_s<seed>.yaml (real multi-process runs) and configs/full/base.yaml.

Differences from configs/config.yaml: data.group_by_flow (split by connection), no cap on the federated pool
(orchestration.pool_subsample_size 0), zero-day scores every row of the held-out class, outputs under */full/.
    python3 tools/make_full_configs.py
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
out = ROOT / "configs" / "full"
out.mkdir(parents=True, exist_ok=True)
base = yaml.safe_load(open(ROOT / "configs" / "config.yaml"))
base["data"]["group_by_flow"] = True
base["data"]["min_flows_per_class"] = 20
base["orchestration"]["pool_subsample_size"] = 0
base["evaluation"]["zero_day_max_holdout_rows"] = 10_000_000
HEADER = "# Full-pool run: split by connection, whole federated pool (no 60k cap). Generated by tools/make_full_configs.py; do not edit.\n"


def write(name, cfg):
    (out / name).write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False))


cfg = yaml.safe_load(yaml.safe_dump(base))
cfg["evaluation"]["output_dir"] = "results/full/inprocess"
cfg["logging"]["log_dir"] = "logs/full"
write("base.yaml", cfg)
for clients in (10, 20):
    for seed in (42, 43, 44):
        cfg = yaml.safe_load(yaml.safe_dump(base))
        tag = f"c{clients}_s{seed}"
        cfg["seed"] = seed
        cfg["data"]["num_clients"] = clients
        cfg["orchestration"].update(artifact_dir=f"saved_models/full/{tag}", run_dir=f"runs/full/{tag}/phase_a")
        cfg["evaluation"]["output_dir"] = f"results/full/{tag}"
        cfg["logging"]["log_dir"] = f"logs/full/{tag}"
        write(f"{tag}.yaml", cfg)
print(sorted(p.name for p in out.iterdir()))
