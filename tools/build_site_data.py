"""Build docs/data.js from results/*.csv|json (run from the repo root after the evaluation scripts) -- no hand-typed numbers."""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "results")


def num(v):
    if v == "" or v is None:
        return None
    try:
        f = float(v)
        return int(f) if f.is_integer() and "." not in v and "e" not in v.lower() else f
    except ValueError:
        return v


def read_csv(name):
    with open(os.path.join(D, name)) as fh:
        return [{k: num(v) for k, v in row.items()} for row in csv.DictReader(fh)]


cm = json.load(open(os.path.join(D, "classifier_comparison_confusion_matrices.json")))
summary = json.load(open(os.path.join(D, "classifier_comparison_summary.json")))

out = {
    "classNames": cm["class_names"],
    "cmBoost": cm["boosting"],
    "cmDl": cm["dl_classifier"],
    "summary": summary,
    "perClassCompare": read_csv("classifier_comparison_per_class.csv"),
    "sweep": read_csv("poisoning_resistance_sweep.csv"),
    "zeroDay": read_csv("zero_day_holdout.csv"),
    "stageReport": read_csv("per_class_stage_report.csv"),
    "multiseed": read_csv("multiseed_20_30_check.csv"),
    "ablation": read_csv("ablation_table.csv"),
    "ablationPerClass": read_csv("ablation_per_class_recall.csv"),
}

# Classifier-accuracy experiments (experiments/accuracy): one JSON per run.
ACC = os.path.join(ROOT, "experiments", "accuracy", "results")
KEEP = ("feature_set", "split", "seed", "n_features", "rows", "train_rows", "test_rows", "sample",
        "balanced_weights", "train_fraction", "accuracy", "macro_f1", "weighted_f1", "ambiguous_share",
        "ceiling_accuracy", "ceiling_macro_recall", "best_iteration", "train_seconds", "classes_scored")
runs = {}
for fn in sorted(os.listdir(ACC)):
    if fn.endswith(".json"):
        r = json.load(open(os.path.join(ACC, fn)))
        runs[fn[:-5]] = {k: r.get(k) for k in KEEP}


def detail(name):
    r = json.load(open(os.path.join(ACC, name + ".json")))
    return {"classes": r["classes"], "perClass": r["per_class"], "cm": r["confusion_matrix"]}


out["accuracy"] = {"runs": runs, "final": detail("full_grouped_bal_s42"), "base": detail("base_grouped_s42"),
                   "finalRandom": detail("full_bal_s42")}

with open(os.path.join(ROOT, "docs", "data.js"), "w") as fh:
    fh.write("// Generated by build_data.py from the real result files. Do not edit by hand.\n")
    fh.write("window.FLIDS = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("wrote data.js", os.path.getsize(os.path.join(ROOT, "docs", "data.js")), "bytes")
print({k: (len(v) if hasattr(v, "__len__") else v) for k, v in out.items()})
print(out["ablationPerClass"][0], out["zeroDay"][0].keys())
